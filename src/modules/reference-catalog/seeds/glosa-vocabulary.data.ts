/**
 * Refuerzo de VOCABULARIO para las hojas que ya existían.
 *
 * Cuarto artefacto del catálogo y el que más filas aporta. Los tres anteriores
 * cubren cada uno una capa: `expense-category-tree` el dominio, `bank-dialect`
 * la forma en que siete bancos rotulan, `bolivian-merchants` a quién se le pagó.
 * Lo que faltaba es la ANCHURA dentro de cada rubro: una hoja con ocho ejemplos
 * reconoce ocho maneras de decir lo mismo, y un extracto trae treinta.
 *
 * ## Por qué esto y no más hojas
 *
 * Añadir hojas y añadir ejemplos NO son la misma jugada. Una hoja nueva sólo
 * ayuda si el banco escribe distinto; si escribe igual, las dos hojas se
 * reparten la confianza y las dos se quedan por debajo de su umbral —está medido
 * en este mismo árbol con `PAGO SERVICIOS`—. Un ejemplo nuevo, en cambio, nunca
 * quita: acerca la hoja a una forma que antes no reconocía y no acerca a ninguna
 * otra. Por eso la cobertura crece aquí y el número de hojas crece poco.
 *
 * ## De dónde salen estas glosas
 *
 * De tres sitios, y ninguno es la imaginación:
 *
 * - **Las plantillas de los bancos ya observadas**, extendidas al resto de los
 *   rubros. Si el BNB escribe `DEBITO EN CUENTA POR COMPRA ATM/POS` para un
 *   supermercado, escribe lo mismo para una óptica.
 * - **Los nombres del mercado boliviano** que faltaban: cooperativas eléctricas,
 *   universidades, aseguradoras, aerolíneas, cadenas de farmacias.
 * - **El léxico administrativo**: formularios del SIN, boletas, planillas y
 *   comprobantes que aparecen escritos tal cual en la glosa.
 *
 * ## Qué NO se siembra
 *
 * Nombres de personas reales, números de documento y referencias: el
 * normalizador los retira antes de clasificar y sembrarlos acercaría cada
 * categoría a cualquier glosa que mencione a alguien. Tampoco cabeceras
 * genéricas —`PAGO`, `DEBITO`, `VARIOS`— que no dicen el rubro: obligarían a
 * elegir donde no hay nada que elegir, que es justo lo que la abstención existe
 * para evitar.
 */

